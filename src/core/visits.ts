export interface VisitRecord { turns: Exchange[]; choice?: Commission }
export function visitRecord(s: GameState, i: number): VisitRecord {
  const book = s.visits ??= {};
  if (!book[i]) {
    book[i] = { turns: i === 1 ? s.xiaoheTalk ?? [] : [] };
    if (i === 1 && s.xiaoheBlade) book[i].choice = s.xiaoheBlade === "thin" ? 0 : 1;
  }
  return book[i];
}

export function previousVisit(i: number) {
  for (let n = i - 1; n >= 0; n--) if (orders[n].name === orders[i].name) return n;
  return -1;
}

export function receipt(i: number, choice: Commission, grade: string) {
  const line = visits[i].options[choice].reaction;
  const quality = {
    "刘农夫": ["就是这毛棱，回去我得拿布蹭蹭。", "摸着真平顺，我这双老手认得好活。"],
    "小荷": ["不过这刃还有点涩，回灶上得再磨磨。", "这刃走得顺，我手上能觉出来。"],
    "猎户": ["活稍粗了些，我回家再拾掇。", "嘿，这活收拾得真齐整。"],
    "秦军户": ["这处毛边我记下了。", "收得干净。好手艺。"],
    "外乡客": ["有些粗糙，我赶车，就这样吧。", "活做得体面，多谢。"],
  }[orders[i].name];
  if (grade === "瑕疵") return line + quality[0];
  if (grade === "精良") return line + quality[1];
  return line;
}


export function questionKey(text: string) {
  return text.normalize("NFKC").replace(/[\p{P}\s]/gu, "");
}

export function repeatsQuestion(candidate: string, known: string) {
  const next = questionKey(candidate);
  const previous = questionKey(known);
  return !!next && (previous === next ||
    (previous.length >= 6 && next.includes(previous)) ||
    (next.length >= 6 && previous.includes(next)));
}
